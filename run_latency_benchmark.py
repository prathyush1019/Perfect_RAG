def main():
    print("=" * 70)
    print("🚀 BENCHMARK: Latency Profiling for All 8 Embedding Models")
    print(f"📊 Dataset: {len(QUESTIONS)} Questions (~20 words each)")
    print("=" * 70)

    # Verify question word counts
    word_counts = [len(q.split()) for q in QUESTIONS]
    avg_words = sum(word_counts) / len(word_counts)
    print(f"Question Word Counts: Min={min(word_counts)}, Max={max(word_counts)}, Avg={avg_words:.1f} words")
    for i, q in enumerate(QUESTIONS, 1):
        print(f"  Q{i:02d} ({len(q.split())} words): {q[:60]}...")

    embedder = CloudflareEmbedder(enable_mock_fallback=False)
    results = {}

    warmup_q = "This is a quick warmup prompt to initialize the TLS connection pool and edge worker runtime."

    for model_id, cfg in ALL_CLOUDFLARE_MODELS.items():
        print("\n" + "-" * 70)
        print(f"🔹 MODEL: {cfg.display_name} ({model_id})")
        print(f"   Provider: {cfg.provider} | Dims: {cfg.dimensions} | Max Tokens: {cfg.max_tokens}")
        print("-" * 70)

        # Warmup call
        print("   [Warmup] Pre-heating edge worker & TCP connection...")
        try:
            _, w_lat = embedder.embed_texts([warmup_q], model_id=model_id, batch_size=1, is_warmup=True)
            print(f"   [Warmup] Ready ({w_lat:.1f}ms)")
        except Exception as e:
            print(f"   [Warmup Warning] {e}")

        latencies_ms = []
        wall_times_ms = []

        print(f"   [Testing] Running {len(QUESTIONS)} live embedding queries...")
        for idx, question in enumerate(QUESTIONS, 1):
            t0 = time.perf_counter()
            try:
                vecs, api_lat = embedder.embed_texts([question], model_id=model_id, batch_size=1)
                wall_ms = (time.perf_counter() - t0) * 1000.0

                if not vecs or len(vecs[0]) != cfg.dimensions:
                    print(f"   ⚠️ Warning: Expected {cfg.dimensions} dims, got {len(vecs[0]) if vecs else 0}")

                latencies_ms.append(api_lat)
                wall_times_ms.append(wall_ms)

                if idx % 5 == 0 or idx == len(QUESTIONS):
                    print(f"      Progress: {idx}/{len(QUESTIONS)} completed | Last Latency: {api_lat:.1f}ms (Wall: {wall_ms:.1f}ms)")

            except Exception as e:
                print(f"   ❌ Query {idx} Failed: {e}")
                time.sleep(1.0)

            time.sleep(0.04)  # Small pacing gap

        if not latencies_ms:
            print(f"   ❌ All queries failed for {model_id}")
            continue

        arr = np.array(latencies_ms)
        wall_arr = np.array(wall_times_ms)

        stats = {
            "model_id": model_id,
            "display_name": cfg.display_name,
            "provider": cfg.provider,
            "dimensions": cfg.dimensions,
            "num_queries": len(latencies_ms),
            "min_ms": round(float(np.min(arr)), 2),
            "max_ms": round(float(np.max(arr)), 2),
            "avg_ms": round(float(np.mean(arr)), 2),
            "std_ms": round(float(np.std(arr)), 2),
            "p50_ms": round(float(np.percentile(arr, 50)), 2),
            "p90_ms": round(float(np.percentile(arr, 90)), 2),
            "p99_ms": round(float(np.percentile(arr, 99)), 2),
            "wall_avg_ms": round(float(np.mean(wall_arr)), 2),
            "wall_p50_ms": round(float(np.percentile(wall_arr, 50)), 2),
            "wall_p90_ms": round(float(np.percentile(wall_arr, 90)), 2),
            "wall_p99_ms": round(float(np.percentile(wall_arr, 99)), 2),
            "samples": [round(x, 2) for x in latencies_ms]
        }
        results[model_id] = stats

        print(f"   📊 STATS (API): Min={stats['min_ms']}ms | Avg={stats['avg_ms']}ms | p50={stats['p50_ms']}ms | p90={stats['p90_ms']}ms | p99={stats['p99_ms']}ms | Max={stats['max_ms']}ms")

    # Output json
    out_file = os.path.join(BASE_DIR, "benchmark_latency_report.json")
    with open(out_file, "w", encoding="utf-8") as f:
        json.dump(results, f, indent=2)

    print("\n" + "=" * 70)
    print(f"✅ BENCHMARK COMPLETE! Results saved to {out_file}")
    print("=" * 70)

if __name__ == "__main__":
    main()
